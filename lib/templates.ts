function wash(
  w: number,
  h: number,
  a: string,
  b: string,
  extra = "",
  angle = "x2=\"0\" y2=\"1\"",
): string {
  return (
    "data:image/svg+xml;utf8," +
    encodeURIComponent(
      `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}"><defs><linearGradient id="g" x1="0" y1="0" ${angle}><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient></defs><rect width="100%" height="100%" fill="url(#g)"/>${extra}</svg>`,
    )
  );
}

function pageSpec(
  width: number,
  height: number,
  background: string,
  extras: Partial<Page> = {},
): Page {
  const base = createDefaultPage();
  return {
    ...base,
    width,
    height,
    background,
    header: { ...base.header, enabled: false },
    footer: { ...base.footer, enabled: false },
    ruler: true,
    ...extras,
  };
}

